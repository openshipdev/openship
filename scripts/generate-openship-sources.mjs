import { lstat, readFile, readlink, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const declarationPath = path.join(projectRoot, "openship.sources.json");
const outputPath = path.join(projectRoot, "lib", "openship-sources.generated.js");
const utf8Decoder = new TextDecoder("utf-8", { fatal: true });

const mediaTypes = new Map([
  [".css", "text/css; charset=utf-8"],
  [".js", "text/javascript; charset=utf-8"],
  [".json", "application/json; charset=utf-8"],
  [".md", "text/markdown; charset=utf-8"],
  [".mjs", "text/javascript; charset=utf-8"],
  [".png", "image/png"],
  [".ts", "text/typescript; charset=utf-8"],
  [".tsx", "text/tsx; charset=utf-8"],
  [".yml", "application/yaml; charset=utf-8"],
  [".yaml", "application/yaml; charset=utf-8"],
]);

const secretPathPattern = /(^|\/)(?:\.env(?:\.|$)|\.git(?:\/|$)|\.next(?:\/|$)|node_modules(?:\/|$)|(?:[^/]*(?:credential|secret|private[-_]?key)[^/]*)|id_(?:rsa|dsa|ecdsa|ed25519)(?:\.|$)|[^/]+\.(?:key|pem|p12|pfx))/i;

function compareUtf8(left, right) {
  return Buffer.compare(Buffer.from(left), Buffer.from(right));
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function assertSafeDeclaredPath(filePath) {
  if (
    !filePath ||
    filePath !== filePath.normalize("NFC") ||
    Buffer.byteLength(filePath) > 512 ||
    filePath.startsWith("/") ||
    filePath.includes("\\") ||
    filePath.includes("\0") ||
    filePath.split("/").some((part) => !part || part === "." || part === "..")
  ) {
    throw new Error(`Unsafe OpenShip source path: ${JSON.stringify(filePath)}`);
  }
  if (secretPathPattern.test(filePath)) {
    throw new Error(`Refusing secret-shaped OpenShip source path: ${JSON.stringify(filePath)}`);
  }
}

function encode(bytes) {
  try {
    const content = utf8Decoder.decode(bytes);
    if (Buffer.from(content, "utf8").equals(bytes)) return { encoding: "utf-8", content };
  } catch {
    // Binary sources are transported as canonical, padded base64.
  }
  return { encoding: "base64", content: bytes.toString("base64") };
}

async function generate() {
  const declaration = JSON.parse(await readFile(declarationPath, "utf8"));
  if (!declaration.project?.name || !declaration.project?.description) {
    throw new Error("openship.sources.json requires project.name and project.description");
  }
  if (!Array.isArray(declaration.files) || declaration.files.length === 0) {
    throw new Error("openship.sources.json requires a non-empty files allowlist");
  }

  const sortedPaths = [...declaration.files].sort(compareUtf8);
  if (new Set(sortedPaths).size !== sortedPaths.length) {
    throw new Error("openship.sources.json contains duplicate paths");
  }
  if (!declaration.files.every((filePath, index) => filePath === sortedPaths[index])) {
    throw new Error("openship.sources.json paths must be sorted by ascending UTF-8 bytes");
  }

  const files = [];
  const bundleFiles = {};
  for (const filePath of sortedPaths) {
    assertSafeDeclaredPath(filePath);
    const absolutePath = path.join(projectRoot, filePath);
    const metadata = await lstat(absolutePath);
    if (!metadata.isFile() && !metadata.isSymbolicLink()) {
      throw new Error(`OpenShip source path is not a file or symlink: ${filePath}`);
    }

    const bytes = await readFile(absolutePath);
    const encoded = encode(bytes);
    const entry = {
      path: filePath,
      size: bytes.length,
      sha256: sha256(bytes),
      encoding: encoded.encoding,
      mediaType: mediaTypes.get(path.extname(filePath).toLowerCase()) ?? "application/octet-stream",
      type: metadata.isSymbolicLink() ? "symlink" : "file",
    };
    if (metadata.isSymbolicLink()) {
      const target = path.posix.normalize(path.posix.join(path.posix.dirname(filePath), await readlink(absolutePath)));
      assertSafeDeclaredPath(target);
      entry.target = target;
    }
    files.push(entry);
    bundleFiles[filePath] = encoded;
  }

  const digestInput = files.map((file) => `${file.path}\0${file.sha256}\n`).join("");
  const digest = `sha256:${sha256(digestInput)}`;
  const manifest = {
    openship: "1.0",
    capability: "sources",
    generatedAt: new Date().toISOString(),
    digest,
    project: declaration.project,
    fileSet: "openship.sources.json",
    totals: {
      files: files.length,
      bytes: files.reduce((total, file) => total + file.size, 0),
    },
    files,
  };
  const bundle = {
    openship: "1.0",
    capability: "sources",
    digest,
    files: bundleFiles,
  };

  const moduleSource = [
    "// Generated by scripts/generate-openship-sources.mjs. Do not edit.",
    `export const sourcesManifest = ${JSON.stringify(manifest)};`,
    `export const sourcesBundle = ${JSON.stringify(bundle)};`,
    "",
  ].join("\n");
  await writeFile(outputPath, moduleSource, "utf8");
  process.stdout.write(`Generated OpenShip Sources ${digest} (${files.length} files, ${manifest.totals.bytes} bytes)\n`);
}

await generate();
